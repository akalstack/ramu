export type Strings = typeof en

/** Puts values into `{0}`, `{1}` placeholders of a string above. */
export function fill(text: string, ...values: (string | number)[]): string {
  return text.replace(/\{(\d+)\}/g, (_, index) => String(values[Number(index)] ?? ''))
}

export function useT(): Strings {
  return useStore().language === 'id' ? id : en
}

export function ago(at: number): string {
  const s = Math.max(0, Math.round((Date.now() - at) / 1000))
  if (s < 60) return 'now'
  const m = Math.round(s / 60)
  if (m < 60) return `${m}m`
  const h = Math.round(m / 60)
  if (h < 24) return `${h}h`
  return `${Math.round(h / 24)}d`
}

export function until(at: number): string {
  const m = Math.max(0, Math.round((at - Date.now()) / 60_000))
  if (m < 60) return `${m}m`
  const h = Math.floor(m / 60)
  if (h < 24) return `${h}h ${m % 60}m`
  return `${Math.round(h / 24)}d`
}
