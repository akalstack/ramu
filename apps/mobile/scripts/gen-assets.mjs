// Copies the desktop's brand and provider SVGs into a TS module for react-native-svg.
// Run after changing assets/wordmark.svg, apps/web/src/assets/providers/*.svg or apps/web/src/assets/os/*.svg.
import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('../../../', import.meta.url)
const read = (path) => readFileSync(new URL(path, root), 'utf8')
const clean = (svg) =>
  svg
    .replace(/<\?xml[^>]*>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<title>[\s\S]*?<\/title>/g, '')
    // CSS classes and fixed text colors don't apply in react-native-svg; the root
    // fill/color props from the theme take over instead.
    .replace(/<defs>\s*<style>[\s\S]*?<\/style>\s*<\/defs>/g, '')
    .replace(/ class="[^"]*"/g, '')
    // SvgXml camel-cases attributes, which React DOM rejects for aria-*; labels live on the wrapper.
    .replace(/ (role|aria-label)="[^"]*"/g, '')
    .replace(/ color="#f5f5f7"/g, '')
    // react-native-svg has no `inherit` paint on iOS; currentColor follows the root color prop.
    .replace(/fill="inherit"/g, 'fill="currentColor"')
    .replace(/\s+/g, ' ')
    .trim()

const startup = read('assets/startup-logo.svg')
const letters = startup.slice(
  startup.indexOf('<g class="startup-letters"'),
  startup.indexOf('<circle class="startup-dot"'),
)
const svgs = {
  startupLetters: clean(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 431.579 136">${letters}</svg>`),
  wordmark: clean(read('assets/wordmark.svg')),
  'claude-code': clean(read('apps/web/src/assets/providers/claude.svg')),
  codex: clean(read('apps/web/src/assets/providers/openai.svg')),
  opencode: clean(read('apps/web/src/assets/providers/opencode.svg')),
  cursor: clean(read('apps/web/src/assets/providers/cursor.svg')),
  antigravity: clean(read('apps/web/src/assets/providers/antigravity.svg')),
  // Operating system marks shared with the desktop's device icons (Simple Icons, CC0).
  ...Object.fromEntries(
    ['apple', 'android', 'ubuntu', 'debian', 'fedora', 'arch', 'mint', 'redhat', 'raspberrypi', 'linux', 'windows'].map(
      (mark) => [`os:${mark}`, clean(read(`apps/web/src/assets/os/${mark}.svg`))],
    ),
  ),
}

const body = Object.entries(svgs)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join('\n')
writeFileSync(
  new URL('../src/assets/svgs.ts', import.meta.url),
  `// Generated by scripts/gen-assets.mjs from assets/ and apps/web/src/assets/providers/. Do not edit.\nexport const svgs = {\n${body}\n} as const\n`,
)
