// Setting a project up on Fly.io, which has no Git integration: create the app on the connected account, keep a deploy
// token limited to that app in the repository's GitHub Actions secrets, and open one pull request with the fly.toml,
// Dockerfile and deploy job the repository lacks. Merging it deploys; every later merge deploys again.
import { flyAppName, flyToml, flyTomlApp, flyWorkflow, FLY_SECRET, FLY_WORKFLOW_PATH } from '@ramu/shared/flyDeploy'
import { DOCKER_MANIFESTS, DOCKERIGNORE, exposedPort, serverDockerfile } from '@ramu/shared/serverDeploy'
import type { DeployLinkResult } from '@ramu/shared/types/deploy'
import { factsAt } from '../ci/setup'
import { commitBranchInfo, fetchedBranch, git } from '../git'
import { existsAt, proposeFile, type ProposedChange } from '../proposeFile'
import { DeployError } from './adapter'
import type { HostingAccounts } from './accounts'
import { flyApi } from './fly'
import type { ServerSetupHost } from './serverSetup'
import type { DeployService } from './service'

const BRANCH = 'ramu/deploy-to-fly'
const CI_PATH = '.github/workflows/ci.yml'

export class FlySetup {
  constructor(
    private readonly accounts: HostingAccounts,
    private readonly service: DeployService,
    private readonly host: ServerSetupHost,
    private readonly fly: ReturnType<typeof flyApi> = flyApi(),
  ) {}

  /** The files the default branch lacks, the port the app listens on, and the app its fly.toml names. */
  private async plan(root: string, ref: string, defaultBranch: string, wanted: string) {
    const facts = await factsAt(root, ref, DOCKER_MANIFESTS)
    const files: ProposedChange['files'] = []
    const notes: string[] = []
    const existingToml = await git(root, ['cat-file', 'blob', `${ref}:fly.toml`]).catch(() => null)
    const app = (existingToml !== null ? flyTomlApp(existingToml) : null) ?? wanted
    let port: number | null
    if (facts.files.includes('Dockerfile')) {
      port = exposedPort(await git(root, ['cat-file', 'blob', `${ref}:Dockerfile`]).catch(() => ''))
      if (!port && existingToml === null)
        throw new Error('The Dockerfile names no port. Add an EXPOSE line with the port the app listens on.')
    } else {
      const dockerfile = serverDockerfile(facts)
      if (!dockerfile)
        throw new Error(
          'Ramu cannot tell how this app starts. Ask an agent to add a Dockerfile with an EXPOSE line, then link Fly.io again.',
        )
      port = dockerfile.port
      files.push({ path: 'Dockerfile', content: dockerfile.content })
      notes.push(`\`Dockerfile\` ${dockerfile.summary}.`)
      if (!facts.files.includes('.dockerignore')) {
        files.push({ path: '.dockerignore', content: DOCKERIGNORE })
        notes.push('`.dockerignore` keeps `.env` files and installed dependencies out of the image.')
      }
    }
    if (existingToml === null) {
      files.push({ path: 'fly.toml', content: flyToml(app, port ?? 8080) })
      notes.push(
        `\`fly.toml\` names the app \`${app}\`, serves it over HTTPS on port ${port ?? 8080} and stops its machines while nobody uses it.`,
      )
    }
    const workflow = await git(root, ['cat-file', 'blob', `${ref}:${FLY_WORKFLOW_PATH}`]).catch(() => null)
    if (workflow === null) {
      const afterCi = await existsAt(root, ref, CI_PATH)
      files.push({ path: FLY_WORKFLOW_PATH, content: flyWorkflow({ app, defaultBranch, afterCi }) })
      notes.push(
        `\`${FLY_WORKFLOW_PATH}\` ${afterCi ? 'runs after CI passes' : 'runs on every push'} on \`${defaultBranch}\`: \`flyctl deploy\` builds the image on Fly.io’s builders, labelled with the commit, and releases it.`,
      )
    } else if (!workflow.includes('Generated by Ramu'))
      throw new Error(`${FLY_WORKFLOW_PATH} already exists and is not Ramu’s deploy job. Rename it, then try again.`)
    return { files, notes, app }
  }

  /**
   * Sets a project up on the connected Fly.io account: the app, its deploy token in the repository's Actions secrets,
   * the pull request with the files the repository lacks, then the binding. Each step can run again safely.
   */
  async link(projectId: string, repoId: string, name: string): Promise<DeployLinkResult> {
    const { auth, accountId, defaultScope } = await this.accounts.auth('fly')
    if (!defaultScope) throw new DeployError('This Fly.io account has no organization to create apps in.', 'not-found')
    const { link, root } = await this.host.repository(projectId, repoId)
    const repository = `${link.owner}/${link.name}`
    const defaultBranch = (await commitBranchInfo(root)).defaultBranch ?? link.productionBranch
    const { ref } = await fetchedBranch(root, defaultBranch)
    // Linking again keeps the app made the first time rather than creating another.
    const earlier = this.service.binding(projectId)
    const wanted =
      earlier?.platform === 'fly' && earlier.repository === repository ? earlier.siteName : flyAppName(name)
    const plan = await this.plan(root, ref, defaultBranch, wanted)
    const app = (await this.fly.appExists(auth, plan.app))
      ? plan.app
      : await this.fly.createApp(auth, plan.app, defaultScope)
    // A suffixed name must reach the generated files too.
    const files =
      app === plan.app
        ? plan.files
        : plan.files.map((file) =>
            file.path === 'fly.toml'
              ? { ...file, content: file.content.replace(`app = "${plan.app}"`, `app = "${app}"`) }
              : file.path === FLY_WORKFLOW_PATH
                ? { ...file, content: file.content.replace(`APP: ${plan.app}`, `APP: ${app}`) }
                : file,
          )
    await this.host.actionsSecrets(root).set('ci', { [FLY_SECRET]: await this.fly.deployToken(auth, app) })
    const { url } = await proposeFile(root, BRANCH, async () => ({
      files,
      commit: `ci: deploy to Fly.io\n\n${files.map((file) => `Adds ${file.path}.`).join('\n')}\n`,
      title: 'Deploy to Fly.io',
      body: [
        ...plan.notes,
        `A deploy token limited to the \`${app}\` app is in this repository’s Actions secrets (${FLY_SECRET}). The app’s variables are Fly.io secrets, not in the image.`,
        'Merge this to deploy; every later merge deploys again.',
      ].join('\n\n'),
    }))
    this.service.bind(projectId, {
      platform: 'fly',
      siteId: repository,
      siteName: app,
      repository,
      productionBranch: defaultBranch,
      accountId: accountId ?? `org:${defaultScope}`,
      scope: defaultScope,
    })
    return { deployment: await this.service.project(projectId), pullRequest: url }
  }
}
