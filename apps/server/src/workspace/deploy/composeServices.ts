// The services beside an app on the person's own server, taken from the repository's Compose file: the ones that run a
// published image (a database, a cache, a worker image), never one Ramu builds, which is the app itself. Their ports are
// dropped, so they are reachable only by the app on their own network, never from the internet.
import { parse, stringify } from 'yaml'

export const COMPOSE_FILES = ['compose.yaml', 'compose.yml', 'docker-compose.yaml', 'docker-compose.yml'] as const
/** Where the setup pull request keeps the services, which the deploy job sends to the server. */
export const SERVICES_PATH = 'deploy/services.yml'

type Service = Record<string, unknown> & { image?: unknown; build?: unknown; ports?: unknown; volumes?: unknown }

/** The image-based services of a Compose file, as a Compose file of their own; null when there are none. */
export function composeServices(text: string): { yaml: string; names: string[] } | null {
  let parsed: { services?: Record<string, Service>; volumes?: Record<string, unknown> } | null
  try {
    parsed = parse(text) as typeof parsed
  } catch {
    return null
  }
  const kept: Record<string, Service> = {}
  for (const [name, service] of Object.entries(parsed?.services ?? {})) {
    if (!service || typeof service.image !== 'string' || service.build !== undefined) continue
    if (!/^[a-z0-9][a-z0-9_.-]{0,62}$/.test(name)) continue
    const { ports: _ports, container_name: _name, ...rest } = service as Service & { container_name?: unknown }
    kept[name] = { ...rest, restart: rest.restart ?? 'unless-stopped' }
  }
  const names = Object.keys(kept)
  if (!names.length) return null
  // Named volumes the kept services use stay declared, so their data survives a redeploy.
  const used = new Set(
    names.flatMap((name) =>
      (Array.isArray(kept[name]!.volumes) ? (kept[name]!.volumes as unknown[]) : [])
        .map((volume) => (typeof volume === 'string' ? volume.split(':')[0]! : ''))
        .filter((volume) => volume && !volume.startsWith('.') && !volume.startsWith('/')),
    ),
  )
  const volumes = Object.fromEntries(Object.entries(parsed?.volumes ?? {}).filter(([name]) => used.has(name)))
  return {
    yaml: `# Services beside the app on your server. Generated by Ramu from the Compose file; ports are not published.\n${stringify({ services: kept, ...(Object.keys(volumes).length ? { volumes } : {}) })}`,
    names,
  }
}
