// Setting a project up on Cloudflare Pages: create the Pages project on the connected account, keep the Pages token
// and the account id in the repository's GitHub Actions secrets, and open one pull request with the deploy job.
// Merging it deploys production; every pull request after that gets a preview.
import {
  cloudflareProjectName,
  cloudflareWorkflow,
  CLOUDFLARE_SECRETS,
  CLOUDFLARE_WORKFLOW_PATH,
} from '@ramu/shared/cloudflareDeploy'
import { pagesBuild } from '@ramu/shared/pagesDeploy'
import type { DeployLinkResult } from '@ramu/shared/types/deploy'
import { commitBranchInfo, fetchedBranch, git } from '../git'
import { existsAt, proposeFile } from '../proposeFile'
import { DeployError } from './adapter'
import type { HostingAccounts } from './accounts'
import { cloudflareApi } from './cloudflare'
import type { ServerSetupHost } from './serverSetup'
import type { DeployService } from './service'

const BRANCH = 'ramu/deploy-to-cloudflare'
const CI_PATH = '.github/workflows/ci.yml'

export class CloudflareSetup {
  constructor(
    private readonly accounts: HostingAccounts,
    private readonly service: DeployService,
    private readonly host: ServerSetupHost,
    private readonly cloudflare: ReturnType<typeof cloudflareApi> = cloudflareApi(),
  ) {}

  async link(projectId: string, repoId: string, name: string): Promise<DeployLinkResult> {
    const { auth, accountId, defaultScope: account } = await this.accounts.auth('cloudflare')
    if (!account) throw new DeployError('This Cloudflare token reaches no account.', 'missing-permission')
    const { link, root } = await this.host.repository(projectId, repoId)
    const repository = `${link.owner}/${link.name}`
    const defaultBranch = (await commitBranchInfo(root)).defaultBranch ?? link.productionBranch
    const { ref } = await fetchedBranch(root, defaultBranch)
    const files = (await git(root, ['ls-tree', '--name-only', ref])).split('\n').filter(Boolean)
    const manifest = files.includes('package.json')
      ? await git(root, ['cat-file', 'blob', `${ref}:package.json`]).catch(() => null)
      : null
    const build = pagesBuild(files, manifest)
    if (!build && !files.some((file) => /^index\.html?$/i.test(file)))
      throw new Error(
        'Ramu cannot tell how this site builds. Cloudflare Pages serves static sites: add a build script that writes the site, or an index.html.',
      )
    const existing = await git(root, ['cat-file', 'blob', `${ref}:${CLOUDFLARE_WORKFLOW_PATH}`]).catch(() => null)
    if (existing !== null && !existing.includes('Generated by Ramu'))
      throw new Error(
        `${CLOUDFLARE_WORKFLOW_PATH} already exists and is not Ramu’s deploy job. Rename it, then try again.`,
      )
    // Linking again keeps the Pages project made the first time.
    const earlier = this.service.binding(projectId)
    const project =
      earlier?.platform === 'cloudflare' && earlier.repository === repository
        ? earlier.siteName
        : cloudflareProjectName(name)
    if (!(await this.cloudflare.projectExists(auth, account, project)))
      await this.cloudflare.createProject(auth, account, project, defaultBranch)
    await this.host
      .actionsSecrets(root)
      .set('ci', { [CLOUDFLARE_SECRETS.token]: auth.token, [CLOUDFLARE_SECRETS.account]: account })
    let pullRequest: string | null = null
    if (existing === null) {
      const afterCi = await existsAt(root, ref, CI_PATH)
      const { url } = await proposeFile(root, BRANCH, async () => ({
        files: [
          { path: CLOUDFLARE_WORKFLOW_PATH, content: cloudflareWorkflow({ project, defaultBranch, afterCi, build }) },
        ],
        commit: `ci: deploy to Cloudflare Pages\n\nAdds ${CLOUDFLARE_WORKFLOW_PATH}.\n`,
        title: 'Deploy to Cloudflare Pages',
        body: [
          build
            ? `\`${CLOUDFLARE_WORKFLOW_PATH}\` installs with ${build.manager}, runs the build script and uploads \`${build.output}/\` to the \`${project}\` Pages project with wrangler.`
            : `\`${CLOUDFLARE_WORKFLOW_PATH}\` uploads the repository’s files to the \`${project}\` Pages project with wrangler.`,
          `Production deploys ${afterCi ? 'after CI passes' : 'on every push'} on \`${defaultBranch}\`, at https://${project}.pages.dev; each pull request gets a preview.`,
          `The Pages token and the account id are in this repository’s Actions secrets (${CLOUDFLARE_SECRETS.token}, ${CLOUDFLARE_SECRETS.account}).`,
          'Merge this to deploy; every later merge deploys again.',
        ].join('\n\n'),
      }))
      pullRequest = url
    }
    this.service.bind(projectId, {
      platform: 'cloudflare',
      siteId: repository,
      siteName: project,
      repository,
      productionBranch: defaultBranch,
      accountId: accountId ?? account,
      scope: account,
    })
    return { deployment: await this.service.project(projectId), pullRequest }
  }
}
