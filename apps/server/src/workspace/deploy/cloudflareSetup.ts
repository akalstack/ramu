// Setting a project up on Cloudflare Pages: create the Pages project on the connected account, keep the Pages token
// and the account id in the repository's GitHub Actions secrets, and open one pull request with the deploy job.
// Merging it deploys production; every pull request after that gets a preview.
import {
  withWorkerBinding,
  workerName,
  workersWorkflow,
  WORKERS_WORKFLOW_PATH,
  cloudflareProjectName,
  cloudflareWorkflow,
  CLOUDFLARE_SECRETS,
  CLOUDFLARE_WORKFLOW_PATH,
} from '@ramu/shared/cloudflareDeploy'
import { packageManagerOf, pagesBuild } from '@ramu/shared/pagesDeploy'
import type { DeployLinkResult } from '@ramu/shared/types/deploy'
import { commitBranchInfo, fetchedBranch, git } from '../git'
import { existsAt, proposeFile } from '../proposeFile'
import { DeployError } from './adapter'
import type { HostingAccounts } from './accounts'
import { cloudflareApi } from './cloudflare'
import { WORKER_TYPE, workerResource, type WorkerProvider, type WorkerResourceAdapter } from './workerResources'
import type { ServerSetupHost } from './serverSetup'
import type { DeployService } from './service'

const BRANCH = 'ramu/deploy-to-cloudflare'
const CI_PATH = '.github/workflows/ci.yml'

export class CloudflareSetup {
  constructor(
    private readonly accounts: HostingAccounts,
    private readonly service: DeployService,
    private readonly host: ServerSetupHost,
    private readonly cloudflare: ReturnType<typeof cloudflareApi> = cloudflareApi(),
  ) {}

  async link(projectId: string, repoId: string, name: string): Promise<DeployLinkResult> {
    const { auth, accountId, defaultScope: account } = await this.accounts.auth('cloudflare')
    if (!account) throw new DeployError('This Cloudflare token reaches no account.', 'missing-permission')
    const { link, root } = await this.host.repository(projectId, repoId)
    const repository = `${link.owner}/${link.name}`
    const defaultBranch = (await commitBranchInfo(root)).defaultBranch ?? link.productionBranch
    const { ref } = await fetchedBranch(root, defaultBranch)
    const files = (await git(root, ['ls-tree', '--name-only', ref])).split('\n').filter(Boolean)
    const manifest = files.includes('package.json')
      ? await git(root, ['cat-file', 'blob', `${ref}:package.json`]).catch(() => null)
      : null
    const build = pagesBuild(files, manifest)
    if (!build && !files.some((file) => /^index\.html?$/i.test(file)))
      throw new Error(
        'Ramu cannot tell how this site builds. Cloudflare Pages serves static sites: add a build script that writes the site, or an index.html.',
      )
    const existing = await git(root, ['cat-file', 'blob', `${ref}:${CLOUDFLARE_WORKFLOW_PATH}`]).catch(() => null)
    if (existing !== null && !existing.includes('Generated by Ramu'))
      throw new Error(
        `${CLOUDFLARE_WORKFLOW_PATH} already exists and is not Ramu’s deploy job. Rename it, then try again.`,
      )
    // Linking again keeps the Pages project made the first time.
    const earlier = this.service.binding(projectId)
    const project =
      earlier?.platform === 'cloudflare' && earlier.repository === repository
        ? earlier.siteName
        : cloudflareProjectName(name)
    if (!(await this.cloudflare.projectExists(auth, account, project)))
      await this.cloudflare.createProject(auth, account, project, defaultBranch)
    await this.host
      .actionsSecrets(root)
      .set('ci', { [CLOUDFLARE_SECRETS.token]: auth.token, [CLOUDFLARE_SECRETS.account]: account })
    let pullRequest: string | null = null
    if (existing === null) {
      const afterCi = await existsAt(root, ref, CI_PATH)
      const { url } = await proposeFile(root, BRANCH, async () => ({
        files: [
          { path: CLOUDFLARE_WORKFLOW_PATH, content: cloudflareWorkflow({ project, defaultBranch, afterCi, build }) },
        ],
        commit: `ci: deploy to Cloudflare Pages\n\nAdds ${CLOUDFLARE_WORKFLOW_PATH}.\n`,
        title: 'Deploy to Cloudflare Pages',
        body: [
          build
            ? `\`${CLOUDFLARE_WORKFLOW_PATH}\` installs with ${build.manager}, runs the build script and uploads \`${build.output}/\` to the \`${project}\` Pages project with wrangler.`
            : `\`${CLOUDFLARE_WORKFLOW_PATH}\` uploads the repository’s files to the \`${project}\` Pages project with wrangler.`,
          `Production deploys ${afterCi ? 'after CI passes' : 'on every push'} on \`${defaultBranch}\`, at https://${project}.pages.dev; each pull request gets a preview.`,
          `The Pages token and the account id are in this repository’s Actions secrets (${CLOUDFLARE_SECRETS.token}, ${CLOUDFLARE_SECRETS.account}).`,
          'Merge this to deploy; every later merge deploys again.',
        ].join('\n\n'),
      }))
      pullRequest = url
    }
    this.service.bind(projectId, {
      platform: 'cloudflare',
      siteId: repository,
      siteName: project,
      repository,
      productionBranch: defaultBranch,
      accountId: accountId ?? account,
      scope: account,
    })
    return { deployment: await this.service.project(projectId), pullRequest }
  }
}

const WRANGLER_CONFIGS = ['wrangler.toml', 'wrangler.jsonc', 'wrangler.json']

/**
 * Setting a Worker up: the Cloudflare token and account id in the repository's Actions secrets, and one pull request
 * with the job that runs `wrangler deploy`. The Worker and its routes come from the repository's own wrangler config.
 */
export class WorkersSetup {
  constructor(
    private readonly accounts: HostingAccounts,
    private readonly service: DeployService,
    private readonly host: ServerSetupHost,
    private readonly resources: (provider: WorkerProvider) => Pick<WorkerResourceAdapter, 'pair'> = workerResource,
  ) {}

  async link(projectId: string, repoId: string): Promise<DeployLinkResult> {
    const { auth, accountId, defaultScope: account } = await this.accounts.auth('cloudflare-workers')
    if (!account) throw new DeployError('This Cloudflare token reaches no account.', 'missing-permission')
    const { link, root } = await this.host.repository(projectId, repoId)
    const repository = `${link.owner}/${link.name}`
    const defaultBranch = (await commitBranchInfo(root)).defaultBranch ?? link.productionBranch
    const { ref } = await fetchedBranch(root, defaultBranch)
    const files = (await git(root, ['ls-tree', '--name-only', ref])).split('\n').filter(Boolean)
    const config = WRANGLER_CONFIGS.find((name) => files.includes(name))
    const name = config ? workerName(await git(root, ['cat-file', 'blob', `${ref}:${config}`]).catch(() => '')) : null
    if (!name)
      throw new Error(
        'Cloudflare Workers deploys from a wrangler config: add wrangler.toml with the Worker’s name, then try again.',
      )
    const existing = await git(root, ['cat-file', 'blob', `${ref}:${WORKERS_WORKFLOW_PATH}`]).catch(() => null)
    if (existing !== null && !existing.includes('Generated by Ramu'))
      throw new Error(
        `${WORKERS_WORKFLOW_PATH} already exists and is not Ramu’s deploy job. Rename it, then try again.`,
      )
    await this.host
      .actionsSecrets(root)
      .set('ci', { [CLOUDFLARE_SECRETS.token]: auth.token, [CLOUDFLARE_SECRETS.account]: account })
    let pullRequest: string | null = null
    if (existing === null) {
      const afterCi = await existsAt(root, ref, CI_PATH)
      const manager = files.includes('package.json') ? packageManagerOf(files) : null
      const { url } = await proposeFile(root, 'ramu/deploy-to-cloudflare-workers', async () => ({
        files: [{ path: WORKERS_WORKFLOW_PATH, content: workersWorkflow({ defaultBranch, afterCi, manager }) }],
        commit: `ci: deploy to Cloudflare Workers\n\nAdds ${WORKERS_WORKFLOW_PATH}.\n`,
        title: 'Deploy to Cloudflare Workers',
        body: [
          `\`${WORKERS_WORKFLOW_PATH}\` ${manager ? `installs with ${manager} and ` : ''}runs \`wrangler deploy\` for the \`${name}\` Worker from \`${config}\`, ${afterCi ? 'after CI passes' : 'on every push'} on \`${defaultBranch}\`.`,
          `The Cloudflare token and the account id are in this repository’s Actions secrets (${CLOUDFLARE_SECRETS.token}, ${CLOUDFLARE_SECRETS.account}); the token needs Workers Scripts edit.`,
          'Merge this to deploy; every later merge deploys again.',
        ].join('\n\n'),
      }))
      pullRequest = url
    }
    this.service.bind(projectId, {
      platform: 'cloudflare-workers',
      siteId: repository,
      siteName: name,
      repository,
      productionBranch: defaultBranch,
      accountId: accountId ?? account,
      scope: account,
    })
    return { deployment: await this.service.project(projectId), pullRequest }
  }

  /**
   * Binds one of the project's Cloudflare resources to its Worker in a pull request: the entry in the wrangler config
   * (production's resource, and the preview copy for `wrangler dev`), named as the code reads it. For D1, Ramu's deploy
   * job also applies the migrations in `migrations/` before each deploy.
   */
  async proposeBinding(
    projectId: string,
    repoId: string,
    provider: WorkerProvider,
    resourceId: string,
    binding: string,
  ): Promise<{ url: string | null }> {
    const { auth } = await this.accounts.auth(provider)
    const pair = await this.resources(provider).pair(auth, resourceId)
    const type = WORKER_TYPE[provider]
    const { root } = await this.host.repository(projectId, repoId)
    const { url } = await proposeFile(root, `ramu/bind-${binding.toLowerCase()}`, async (ref, defaultBranch) => {
      const files = (await git(root, ['ls-tree', '--name-only', ref])).split('\n').filter(Boolean)
      const config = WRANGLER_CONFIGS.find((name) => files.includes(name))
      if (!config) throw new Error('This repository has no wrangler config to add the binding to.')
      const text = await git(root, ['cat-file', 'blob', `${ref}:${config}`])
      const workflow = await git(root, ['cat-file', 'blob', `${ref}:${WORKERS_WORKFLOW_PATH}`]).catch(() => null)
      const migrates = type === 'D1Database' && !!workflow?.includes('Generated by Ramu')
      return {
        files: [
          { path: config, content: withWorkerBinding(config, text, type, binding, pair), replaces: true },
          ...(migrates
            ? [
                {
                  path: WORKERS_WORKFLOW_PATH,
                  content: workersWorkflow({
                    defaultBranch,
                    afterCi: await existsAt(root, ref, CI_PATH),
                    manager: files.includes('package.json') ? packageManagerOf(files) : null,
                    d1: binding,
                  }),
                  replaces: true as const,
                },
              ]
            : []),
        ],
        commit: `build: bind ${pair.name} to the Worker as ${binding}\n\nAdds the ${binding} binding to ${config}.\n`,
        title: `Bind ${pair.name} to the Worker as ${binding}`,
        body: [
          `Binds \`${pair.name}\` to the Worker as \`env.${binding}\` in \`${config}\`. \`wrangler dev\` uses \`${pair.name}-preview\`, so local work never changes production's.`,
          type === 'D1Database'
            ? migrates
              ? `\`${WORKERS_WORKFLOW_PATH}\` now applies the migrations in \`migrations/\` with \`wrangler d1 migrations apply ${binding} --remote\` before each deploy.`
              : `Apply migrations with \`wrangler d1 migrations apply ${binding} --remote\` before deploying.`
            : '',
        ]
          .filter(Boolean)
          .join('\n\n'),
      }
    })
    return { url }
  }
}
