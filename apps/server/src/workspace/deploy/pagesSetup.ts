// Setting a project up on GitHub Pages: open one pull request with the deploy job (built for the site's framework, or
// publishing its files as they are), switch the repository's Pages to publish from GitHub Actions, and bind the
// project. Everything goes through the GitHub account that reaches the repository; merging the pull request deploys.
import { pagesBuild, pagesWorkflow, PAGES_WORKFLOW_PATH } from '@ramu/shared/pagesDeploy'
import type { DeployLinkResult } from '@ramu/shared/types/deploy'
import { commitBranchInfo, fetchedBranch, git } from '../git'
import { existsAt, proposeFile } from '../proposeFile'
import { GITHUB_HEADERS } from './actionsDeploys'
import { DeployError } from './adapter'
import type { HostingAccounts } from './accounts'
import { PAGES_ACCOUNT } from './githubPages'
import type { ServerSetupHost } from './serverSetup'
import type { DeployService } from './service'

const BRANCH = 'ramu/deploy-to-github-pages'
const CI_PATH = '.github/workflows/ci.yml'

export class PagesSetup {
  constructor(
    private readonly accounts: HostingAccounts,
    private readonly service: DeployService,
    private readonly host: Pick<ServerSetupHost, 'repository'>,
    private readonly options: { api?: string; fetch?: typeof fetch } = {},
  ) {}

  /** Turns on Pages publishing from GitHub Actions, or switches an existing Pages site to it. */
  private async enable(repository: string, token: string): Promise<void> {
    const api = this.options.api ?? 'https://api.github.com'
    const request = (method: 'POST' | 'PUT') =>
      (this.options.fetch ?? fetch)(`${api}/repos/${repository}/pages`, {
        method,
        headers: { ...GITHUB_HEADERS, Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
        body: JSON.stringify({ build_type: 'workflow' }),
        redirect: 'error',
        signal: AbortSignal.timeout(20_000),
      })
    let response = await request('POST')
    // 409: the repository already has a Pages site, which is switched to publish from the deploy job.
    if (response.status === 409) response = await request('PUT')
    if (response.ok || response.status === 204) return
    if (response.status === 403 || response.status === 404 || response.status === 422)
      throw new DeployError(
        'GitHub would not turn on Pages for this repository. Pages needs a public repository, or a paid plan for a private one, and admin access.',
        'missing-permission',
        response.status,
      )
    throw new DeployError(
      `GitHub answered ${response.status} turning on Pages. Try again in a moment.`,
      null,
      response.status,
    )
  }

  async link(projectId: string, repoId: string): Promise<DeployLinkResult> {
    const { link, root } = await this.host.repository(projectId, repoId)
    const repository = `${link.owner}/${link.name}`
    const defaultBranch = (await commitBranchInfo(root)).defaultBranch ?? link.productionBranch
    const { ref } = await fetchedBranch(root, defaultBranch)
    const files = (await git(root, ['ls-tree', '--name-only', ref])).split('\n').filter(Boolean)
    const manifest = files.includes('package.json')
      ? await git(root, ['cat-file', 'blob', `${ref}:package.json`]).catch(() => null)
      : null
    const build = pagesBuild(files, manifest)
    if (!build && !files.some((name) => /^index\.html?$/i.test(name)))
      throw new Error(
        'Ramu cannot tell how this site builds. GitHub Pages serves static sites: add a build script that writes the site, or an index.html.',
      )
    const existing = await git(root, ['cat-file', 'blob', `${ref}:${PAGES_WORKFLOW_PATH}`]).catch(() => null)
    if (existing !== null && !existing.includes('Generated by Ramu'))
      throw new Error(`${PAGES_WORKFLOW_PATH} already exists and is not Ramu’s deploy job. Rename it, then try again.`)
    await this.enable(repository, await link.githubToken())
    let pullRequest: string | null = null
    if (existing === null) {
      const afterCi = await existsAt(root, ref, CI_PATH)
      const { url } = await proposeFile(root, BRANCH, async () => ({
        files: [{ path: PAGES_WORKFLOW_PATH, content: pagesWorkflow({ defaultBranch, afterCi, build }) }],
        commit: `ci: deploy to GitHub Pages\n\nAdds ${PAGES_WORKFLOW_PATH}.\n`,
        title: 'Deploy to GitHub Pages',
        body: [
          build
            ? `\`${PAGES_WORKFLOW_PATH}\` installs with ${build.manager}, runs the build script and publishes \`${build.output}/\`.`
            : `\`${PAGES_WORKFLOW_PATH}\` publishes the repository’s files as they are.`,
          `It ${afterCi ? 'runs after CI passes' : 'runs on every push'} on \`${defaultBranch}\`. Pages is set to publish from GitHub Actions.`,
          ...(build?.output === 'out'
            ? ['Next.js needs `output: "export"` in its config to write a static site to `out/`.']
            : []),
          'Merge this to deploy; every later merge deploys again.',
        ].join('\n\n'),
      }))
      pullRequest = url
    }
    if (!this.accounts.connected('github-pages')) await this.accounts.save('github-pages', PAGES_ACCOUNT, 'token')
    this.service.bind(projectId, {
      platform: 'github-pages',
      siteId: repository,
      siteName: repository,
      repository,
      productionBranch: defaultBranch,
      accountId: 'github',
      scope: null,
    })
    return { deployment: await this.service.project(projectId), pullRequest }
  }
}
