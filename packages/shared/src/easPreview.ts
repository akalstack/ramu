// The GitHub Actions job that previews each pull request of an Expo app as an EAS Update. Pure, so the server and the
// tests write the same file.

export type PackageManager = 'npm' | 'pnpm' | 'yarn' | 'bun'

/** The package manager a repository's lockfile names. */
export const packageManagerOf = (files: string[]): PackageManager =>
  files.includes('pnpm-lock.yaml')
    ? 'pnpm'
    : files.includes('yarn.lock')
      ? 'yarn'
      : files.includes('bun.lock') || files.includes('bun.lockb')
        ? 'bun'
        : 'npm'

/** The command that installs a repository's dependencies exactly as its lockfile says. */
const INSTALL: Record<PackageManager, string> = {
  npm: 'npm ci',
  pnpm: 'corepack enable && pnpm install --frozen-lockfile',
  yarn: 'corepack enable && yarn install --immutable',
  bun: 'npm install -g bun && bun install --frozen-lockfile',
}

export const EAS_PREVIEW_WORKFLOW_PATH = '.github/workflows/eas-preview.yml'
/** The repository secret the preview job signs in to EAS with. */
export const EXPO_TOKEN_SECRET = 'EXPO_TOKEN'

/**
 * The job that publishes each pull request's branch as an EAS Update on its own branch and comments a QR code on the
 * pull request. Pull requests from forks get no secrets, so they get no preview.
 */
export function easPreviewWorkflow(manager: PackageManager): string {
  return [
    '# Publishes each pull request as an EAS Update with a QR code. Generated by Ramu; see the Deploy sheet.',
    'name: EAS Update preview',
    'on:',
    '  pull_request:',
    '    types: [opened, synchronize, reopened]',
    'permissions:',
    '  contents: read',
    '  pull-requests: write',
    '',
    'concurrency:',
    '  group: eas-preview-${{ github.event.pull_request.number }}',
    '  cancel-in-progress: true',
    '',
    'jobs:',
    '  preview:',
    '    name: Preview',
    '    if: github.event.pull_request.head.repo.full_name == github.repository',
    '    runs-on: ubuntu-latest',
    '    steps:',
    '      - uses: actions/checkout@v4',
    '      - uses: actions/setup-node@v4',
    '        with:',
    '          node-version: lts/*',
    '      - uses: expo/expo-github-action@v8',
    '        with:',
    '          eas-version: latest',
    `          token: \${{ secrets.${EXPO_TOKEN_SECRET} }}`,
    '      - name: Install',
    `        run: ${INSTALL[manager]}`,
    '      - uses: expo/expo-github-action/preview@v8',
    '        with:',
    '          command: eas update --auto --non-interactive --branch pr-${{ github.event.pull_request.number }}',
    '',
  ].join('\n')
}
