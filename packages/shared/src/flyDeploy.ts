// Deploying to Fly.io, which has no Git integration: a `fly.toml` naming the app and the port it listens on, and a
// GitHub Actions job that runs `flyctl deploy` with an app-scoped deploy token from the repository's secrets. Pure, so
// the deploy sheet, the job and the tests write the same files without a repository or an account.
import { CHOOSE_VERSION_STEP, deployJobTriggers } from './serverDeploy'

/** The workflow file the job lives in, named as `fly launch` names its own; rollbacks and Deploy dispatch it. */
export const FLY_WORKFLOW = 'fly-deploy.yml'
export const FLY_WORKFLOW_PATH = `.github/workflows/${FLY_WORKFLOW}`

/** The repository secret holding the app's deploy token, which flyctl reads by this name. */
export const FLY_SECRET = 'FLY_API_TOKEN'

/** A Fly app name from a project's name: lowercase letters, digits and dashes, as Fly requires. */
export function flyAppName(name: string): string {
  return (
    name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 50) || 'ramu-app'
  )
}

/** The app an existing `fly.toml` names, or null when it names none. */
export function flyTomlApp(toml: string): string | null {
  return /^\s*app\s*=\s*["']([a-z0-9-]{1,63})["']/m.exec(toml)?.[1] ?? null
}

/**
 * A `fly.toml` for the app: HTTPS to the port the container listens on, and machines that stop when idle and start on
 * the next request, so a small app costs little while nobody uses it.
 */
export function flyToml(app: string, port: number): string {
  return [
    '# Fly.io configuration. Generated by Ramu; see https://fly.io/docs/reference/configuration/',
    `app = "${app}"`,
    '',
    '[http_service]',
    `  internal_port = ${port}`,
    '  force_https = true',
    "  auto_stop_machines = 'stop'",
    '  auto_start_machines = true',
    '  min_machines_running = 0',
    '',
  ].join('\n')
}

export interface FlyWorkflowFacts {
  app: string
  defaultBranch: string
  /** The repository has Ramu's CI workflow, so deploys wait for it to pass. */
  afterCi: boolean
}

/**
 * The deploy job: after CI passes on the default branch (or on every push there without CI), `flyctl deploy` builds
 * the image on Fly's builders and labels it with the commit. Dispatching it with an earlier commit's `tag` deploys
 * that commit's image from Fly's registry again without building, which is how Ramu rolls back.
 */
export function flyWorkflow(facts: FlyWorkflowFacts): string {
  return [
    '# Deploys to Fly.io. Generated by Ramu; see the Deploy sheet.',
    'name: Deploy to Fly',
    ...deployJobTriggers(facts.defaultBranch, facts.afterCi),
    'permissions:',
    '  contents: read',
    '',
    'concurrency:',
    '  group: fly-deploy',
    '  cancel-in-progress: false',
    '',
    'jobs:',
    '  deploy:',
    '    name: Deploy',
    "    if: github.event_name != 'workflow_run' || github.event.workflow_run.conclusion == 'success'",
    '    runs-on: ubuntu-latest',
    '    steps:',
    ...CHOOSE_VERSION_STEP,
    '      - uses: actions/checkout@v4',
    '        with:',
    '          ref: ${{ steps.image.outputs.tag }}',
    '      - uses: superfly/flyctl-actions/setup-flyctl@v1',
    '      - name: Deploy',
    '        env:',
    `          FLY_API_TOKEN: \${{ secrets.${FLY_SECRET} }}`,
    `          APP: ${facts.app}`,
    '          TAG: ${{ steps.image.outputs.tag }}',
    '          BUILD: ${{ steps.image.outputs.build }}',
    '        run: |',
    '          if [ "$BUILD" = true ]; then',
    '            flyctl deploy --remote-only --image-label "$TAG"',
    '          else',
    '            flyctl deploy --image "registry.fly.io/$APP:$TAG"',
    '          fi',
    '',
  ].join('\n')
}
