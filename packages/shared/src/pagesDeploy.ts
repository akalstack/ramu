// Deploying a static site to GitHub Pages, which builds nothing itself: a GitHub Actions job that builds the site (when
// it has a build script), uploads the output and publishes it with GitHub's own Pages actions. Pure, so the deploy
// sheet and the tests write the same file without a repository or an account.
import { deployJobTriggers } from './serverDeploy'

/** The workflow file the job lives in; Deploy and rollbacks dispatch it. */
export const PAGES_WORKFLOW = 'pages-deploy.yml'
export const PAGES_WORKFLOW_PATH = `.github/workflows/${PAGES_WORKFLOW}`

export interface PagesBuild {
  /** The package manager the lockfile names. */
  manager: 'npm' | 'pnpm' | 'yarn' | 'bun'
  /** The folder the build writes the site to. */
  output: string
}

/**
 * How a repository builds to a static site: a Node project with a build script, and where its framework writes the
 * output; null for a site of plain files, published as it is.
 */
export function pagesBuild(files: string[], packageJson: string | null): PagesBuild | null {
  if (!packageJson) return null
  let manifest: { scripts?: Record<string, string>; dependencies?: object; devDependencies?: object }
  try {
    manifest = JSON.parse(packageJson) as typeof manifest
  } catch {
    return null
  }
  if (!manifest.scripts?.build) return null
  const uses = (name: string) => name in { ...manifest.dependencies, ...manifest.devDependencies }
  const manager = files.includes('pnpm-lock.yaml')
    ? 'pnpm'
    : files.includes('yarn.lock')
      ? 'yarn'
      : files.includes('bun.lock') || files.includes('bun.lockb')
        ? 'bun'
        : 'npm'
  const output = uses('next')
    ? 'out'
    : uses('react-scripts') || uses('@sveltejs/kit') || uses('@docusaurus/core')
      ? 'build'
      : uses('@11ty/eleventy')
        ? '_site'
        : 'dist'
  return { manager, output }
}

const INSTALL: Record<PagesBuild['manager'], string> = {
  npm: 'npm ci',
  pnpm: 'corepack enable && pnpm install --frozen-lockfile',
  yarn: 'corepack enable && yarn install --immutable',
  bun: 'npm install -g bun && bun install --frozen-lockfile',
}

/** The job steps that pick the commit, check it out and build the site, shared by the static hosting jobs. */
export function staticBuildSteps(build: PagesBuild | null): string[] {
  return [
    '      - name: Choose the commit',
    '        id: commit',
    '        env:',
    '          TAG: ${{ inputs.tag }}',
    '          SHA: ${{ github.event.workflow_run.head_sha || github.sha }}',
    '        run: |',
    '          if [ -n "$TAG" ] && ! printf \'%s\' "$TAG" | grep -Eq \'^[0-9a-f]{40}$\'; then echo "::error::tag must be a full commit SHA"; exit 1; fi',
    '          echo "sha=${TAG:-$SHA}" >> "$GITHUB_OUTPUT"',
    '      - uses: actions/checkout@v4',
    '        with:',
    '          ref: ${{ steps.commit.outputs.sha }}',
    ...(build
      ? [
          '      - uses: actions/setup-node@v4',
          '        with:',
          '          node-version: lts/*',
          '      - name: Install',
          `        run: ${INSTALL[build.manager]}`,
          '      - name: Build',
          `        run: ${build.manager === 'npm' ? 'npm run build' : `${build.manager} run build`}`,
        ]
      : []),
  ]
}

export interface PagesWorkflowFacts {
  defaultBranch: string
  /** The repository has Ramu's CI workflow, so deploys wait for it to pass. */
  afterCi: boolean
  build: PagesBuild | null
}

/**
 * The deploy job: after CI passes on the default branch (or on every push there without CI), build the site at that
 * commit and publish it. Dispatching it with an earlier commit's `tag` builds and publishes that commit, which is how
 * Ramu rolls back.
 */
export function pagesWorkflow(facts: PagesWorkflowFacts): string {
  const build = facts.build
  return [
    '# Deploys to GitHub Pages. Generated by Ramu; see the Deploy sheet.',
    'name: Deploy to GitHub Pages',
    ...deployJobTriggers(facts.defaultBranch, facts.afterCi),
    'permissions:',
    '  contents: read',
    '  pages: write',
    '  id-token: write',
    '',
    'concurrency:',
    '  group: pages',
    '  cancel-in-progress: false',
    '',
    'jobs:',
    '  build:',
    '    name: Build',
    "    if: github.event_name != 'workflow_run' || github.event.workflow_run.conclusion == 'success'",
    '    runs-on: ubuntu-latest',
    '    steps:',
    ...staticBuildSteps(build),
    '      - uses: actions/configure-pages@v5',
    '      - uses: actions/upload-pages-artifact@v3',
    '        with:',
    `          path: ${build ? build.output : '.'}`,
    '  deploy:',
    '    name: Publish',
    '    needs: build',
    '    runs-on: ubuntu-latest',
    '    environment:',
    '      name: github-pages',
    '      url: ${{ steps.deployment.outputs.page_url }}',
    '    steps:',
    '      - uses: actions/deploy-pages@v4',
    '        id: deployment',
    '',
  ].join('\n')
}
