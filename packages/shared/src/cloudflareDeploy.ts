// Deploying a static site to Cloudflare Pages: a GitHub Actions job that builds the site and uploads it with
// `wrangler pages deploy`, using a Pages-only API token from the repository's secrets. Pushes to the default branch
// publish production; pull requests get preview deployments. Pure, so the deploy sheet and the tests write the same file.
import { installCommand, staticBuildSteps, type PagesBuild } from './pagesDeploy'
import { deployJobTriggers } from './serverDeploy'

export const CLOUDFLARE_WORKFLOW = 'cloudflare-deploy.yml'
export const CLOUDFLARE_WORKFLOW_PATH = `.github/workflows/${CLOUDFLARE_WORKFLOW}`

/** The repository secrets wrangler reads. */
export const CLOUDFLARE_SECRETS = { token: 'CLOUDFLARE_API_TOKEN', account: 'CLOUDFLARE_ACCOUNT_ID' } as const

/** A Pages project name from a project's name: lowercase letters, digits and dashes, at most 58 characters. */
export function cloudflareProjectName(name: string): string {
  return (
    name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 58) || 'ramu-site'
  )
}

export interface CloudflareWorkflowFacts {
  project: string
  defaultBranch: string
  /** The repository has Ramu's CI workflow, so production deploys wait for it to pass. */
  afterCi: boolean
  build: PagesBuild | null
}

/**
 * The deploy job: production after CI passes on the default branch (or on every push there without CI) and when
 * dispatched with an earlier commit's `tag`; a preview for each pull request, on its branch's preview address.
 */
export function cloudflareWorkflow(facts: CloudflareWorkflowFacts): string {
  const triggers = deployJobTriggers(facts.defaultBranch, facts.afterCi)
  const on = triggers.indexOf('on:') + 1
  return [
    '# Deploys to Cloudflare Pages. Generated by Ramu; see the Deploy sheet.',
    'name: Deploy to Cloudflare Pages',
    ...triggers.slice(0, on),
    '  pull_request:',
    ...triggers.slice(on),
    'permissions:',
    '  contents: read',
    '  deployments: write',
    '',
    'concurrency:',
    '  group: cloudflare-${{ github.head_ref || github.ref }}',
    '  cancel-in-progress: true',
    '',
    'jobs:',
    '  deploy:',
    '    name: Deploy',
    "    if: github.event_name != 'workflow_run' || github.event.workflow_run.conclusion == 'success'",
    '    runs-on: ubuntu-latest',
    '    steps:',
    ...staticBuildSteps(facts.build),
    '      - uses: cloudflare/wrangler-action@v3',
    '        with:',
    `          apiToken: \${{ secrets.${CLOUDFLARE_SECRETS.token} }}`,
    `          accountId: \${{ secrets.${CLOUDFLARE_SECRETS.account} }}`,
    `          command: pages deploy ${facts.build ? facts.build.output : '.'} --project-name=${facts.project} --branch=\${{ github.head_ref || '${facts.defaultBranch}' }} --commit-hash=\${{ steps.commit.outputs.sha }}`,
    '',
  ].join('\n')
}

export const WORKERS_WORKFLOW = 'cloudflare-workers-deploy.yml'
export const WORKERS_WORKFLOW_PATH = `.github/workflows/${WORKERS_WORKFLOW}`

/** The Worker's name from its wrangler config (TOML or JSON with comments), or null when it names none. */
export function workerName(config: string): string | null {
  const name =
    /^\s*name\s*=\s*["']([a-z0-9-]{1,63})["']/m.exec(config) ?? /"name"\s*:\s*"([a-z0-9-]{1,63})"/.exec(config)
  return name?.[1] ?? null
}

/**
 * The Worker's deploy job: after CI passes on the default branch (or on every push there without CI), install the
 * repository's dependencies and run `wrangler deploy`; dispatched with an earlier commit's `tag`, it deploys that commit.
 */
export function workersWorkflow(facts: {
  defaultBranch: string
  afterCi: boolean
  manager: PagesBuild['manager'] | null
  /** The Worker's D1 binding, whose migrations in `migrations/` are applied before each deploy. */
  d1?: string
}): string {
  return [
    '# Deploys to Cloudflare Workers. Generated by Ramu; see the Deploy sheet.',
    'name: Deploy to Cloudflare Workers',
    ...deployJobTriggers(facts.defaultBranch, facts.afterCi),
    'permissions:',
    '  contents: read',
    '',
    'concurrency:',
    '  group: cloudflare-workers',
    '  cancel-in-progress: false',
    '',
    'jobs:',
    '  deploy:',
    '    name: Deploy',
    "    if: github.event_name != 'workflow_run' || github.event.workflow_run.conclusion == 'success'",
    '    runs-on: ubuntu-latest',
    '    steps:',
    ...staticBuildSteps(null),
    ...(facts.manager
      ? [
          '      - uses: actions/setup-node@v4',
          '        with:',
          '          node-version: lts/*',
          '      - name: Install',
          `        run: ${installCommand(facts.manager)}`,
        ]
      : []),
    ...(facts.d1
      ? [
          '      - name: Apply D1 migrations',
          "        if: hashFiles('migrations/*.sql') != ''",
          '        uses: cloudflare/wrangler-action@v3',
          '        with:',
          `          apiToken: \${{ secrets.${CLOUDFLARE_SECRETS.token} }}`,
          `          accountId: \${{ secrets.${CLOUDFLARE_SECRETS.account} }}`,
          `          command: d1 migrations apply ${facts.d1} --remote`,
        ]
      : []),
    '      - uses: cloudflare/wrangler-action@v3',
    '        with:',
    `          apiToken: \${{ secrets.${CLOUDFLARE_SECRETS.token} }}`,
    `          accountId: \${{ secrets.${CLOUDFLARE_SECRETS.account} }}`,
    '          command: deploy',
    '',
  ].join('\n')
}

/** The Worker types that show which Cloudflare resources its code reads, as in `interface Env { DB: D1Database }`. */
export const WORKER_BINDING_TYPES = ['D1Database', 'KVNamespace', 'R2Bucket'] as const
export type WorkerBindingType = (typeof WORKER_BINDING_TYPES)[number]

/** The binding name used when the code names none. */
export const DEFAULT_BINDING: Record<WorkerBindingType, string> = {
  D1Database: 'DB',
  KVNamespace: 'KV',
  R2Bucket: 'BUCKET',
}

/** The first binding name the code gives each type, from fields typed as one (`DB: D1Database`, `CACHE?: KVNamespace`). */
export function workerBindings(files: readonly { text: string }[]): Partial<Record<WorkerBindingType, string>> {
  const found: Partial<Record<WorkerBindingType, string>> = {}
  for (const { text } of files)
    for (const match of text.matchAll(
      /\b([A-Za-z_][A-Za-z0-9_]{0,62})\s*\??\s*:\s*(D1Database|KVNamespace|R2Bucket)\b/g,
    ))
      found[match[2] as WorkerBindingType] ??= match[1]!
  return found
}

/** A resource and its preview copy, which `wrangler dev` uses so local work never changes production's. */
export interface WorkerPair {
  name: string
  /** D1's and KV's id, or R2's bucket name. */
  id: string
  previewId: string
}

const TABLES: Record<WorkerBindingType, string> = {
  D1Database: 'd1_databases',
  KVNamespace: 'kv_namespaces',
  R2Bucket: 'r2_buckets',
}

function bindingEntry(type: WorkerBindingType, binding: string, pair: WorkerPair): Record<string, string> {
  if (type === 'D1Database')
    return {
      binding,
      database_name: pair.name,
      database_id: pair.id,
      preview_database_id: pair.previewId,
      migrations_dir: 'migrations',
    }
  if (type === 'KVNamespace') return { binding, id: pair.id, preview_id: pair.previewId }
  return { binding, bucket_name: pair.id, preview_bucket_name: pair.previewId }
}

/**
 * The Worker's wrangler config with one binding added: a `[[d1_databases]]`, `[[kv_namespaces]]` or `[[r2_buckets]]`
 * table in wrangler.toml, or an entry in wrangler.json. Refused when the config already has a binding of that name,
 * and for wrangler.jsonc, whose comments a rewrite would lose.
 */
export function withWorkerBinding(
  file: string,
  config: string,
  type: WorkerBindingType,
  binding: string,
  pair: WorkerPair,
): string {
  const table = TABLES[type]
  const entry = bindingEntry(type, binding, pair)
  if (new RegExp(`["']?binding["']?\\s*[=:]\\s*["']${binding}["']`).test(config))
    throw new Error(`${file} already has a binding named ${binding}. Change it there instead.`)
  if (file.endsWith('.toml'))
    return [
      config.replace(/\s*$/, ''),
      '',
      `[[${table}]]`,
      ...Object.entries(entry).map(([key, value]) => `${key} = ${JSON.stringify(value)}`),
      '',
    ].join('\n')
  if (file.endsWith('.json')) {
    const parsed = JSON.parse(config) as Record<string, unknown>
    const list = Array.isArray(parsed[table]) ? (parsed[table] as unknown[]) : []
    return `${JSON.stringify({ ...parsed, [table]: [...list, entry] }, null, 2)}\n`
  }
  throw new Error(
    `Add this to ${file} yourself, since rewriting it would lose its comments: "${table}": [${JSON.stringify(entry)}]`,
  )
}
