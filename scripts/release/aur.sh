#!/usr/bin/env bash
# Writes the PKGBUILD and .SRCINFO of the AUR package `ramu-bin` for one release. The package repackages the release's
# .deb files, so Arch Linux installs the same build Debian and Fedora do, checked against the release's checksums.
#
# Usage: scripts/release/aur.sh <tag> <output dir>
# Needs gh. RAMU_AUR_SUMS=<dir> reads SHA256SUMS-linux-*.txt already on disk instead of downloading them.
set -euo pipefail

tag=${1:?tag, such as v1.1.0-beta.1}
out=${2:?output directory}
repo=${RAMU_RELEASE_REPO:-akalstack/ramu}
version=${tag#v}
# pacman ranks 1.1.0beta.1 before 1.1.0 only without a separator before the letters (1.1.0.beta.1 would rank after).
pkgver=${version//-/}
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

if [ -n "${RAMU_AUR_SUMS:-}" ]; then
  cp "$RAMU_AUR_SUMS"/SHA256SUMS-linux-*.txt "$work/"
else
  gh release download "$tag" --repo "$repo" --pattern 'SHA256SUMS-linux-*.txt' --dir "$work"
fi

# The release names each file `linux-<arch>-<file>`; its checksum list names it the same way.
deb() { # <release arch> <deb arch> -> "<sha256> <file>"
  local line
  line=$(grep -E "linux-$1-ramu_.*_$2\.deb$" "$work/SHA256SUMS-linux-$1.txt" | head -n1)
  [ -n "$line" ] || { echo "No $2 .deb in $tag" >&2; exit 1; }
  # GitHub stores `~` in an asset name as `.`.
  local file
  file=$(basename "${line##* }")
  echo "${line%% *} ${file//\~/.}"
}
read -r x64_sum x64_file <<< "$(deb x64 amd64)"
read -r arm_sum arm_file <<< "$(deb arm64 arm64)"
base="https://github.com/$repo/releases/download/$tag"

depends=(gtk3 libnotify nss xdg-utils at-spi2-core libdrm mesa libxcb libsecret alsa-lib)
optdepends=('gnome-keyring: keeps provider sign-ins in a keyring' 'trash-cli: moves deleted files to the trash')

mkdir -p "$out"
{
  echo "# Maintainer: Ramu contributors <https://github.com/$repo>"
  echo "# Generated by scripts/release/aur.sh in https://github.com/$repo for each release."
  echo "pkgname=ramu-bin"
  echo "pkgver=$pkgver"
  echo "pkgrel=1"
  echo "pkgdesc='Open-source desktop workspace for coding with AI agents'"
  echo "arch=('x86_64' 'aarch64')"
  echo "url='https://getramu.dev'"
  echo "license=('MIT')"
  echo "provides=('ramu')"
  echo "conflicts=('ramu')"
  echo "depends=(${depends[*]})"
  printf 'optdepends=('; printf "'%s' " "${optdepends[@]}" | sed 's/ $//'; echo ')'
  echo "options=('!strip' '!debug')"
  echo "source_x86_64=(\"ramu-$pkgver-x86_64.deb::$base/$x64_file\")"
  echo "source_aarch64=(\"ramu-$pkgver-aarch64.deb::$base/$arm_file\")"
  echo "sha256sums_x86_64=('$x64_sum')"
  echo "sha256sums_aarch64=('$arm_sum')"
  cat <<'EOF'

package() {
  bsdtar -xf data.tar.xz -C "$pkgdir"
  # Chromium's sandbox helper must stay setuid root where user namespaces are off.
  chmod 4755 "$pkgdir/usr/lib/ramu/chrome-sandbox"
  # Debian-only files.
  rm -rf "$pkgdir/usr/share/lintian"
  install -Dm644 "$pkgdir/usr/share/doc/ramu/copyright" "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
}
EOF
} > "$out/PKGBUILD"

# makepkg --printsrcinfo needs Arch; this writes the same fields.
{
  echo "pkgbase = ramu-bin"
  echo "	pkgdesc = Open-source desktop workspace for coding with AI agents"
  echo "	pkgver = $pkgver"
  echo "	pkgrel = 1"
  echo "	url = https://getramu.dev"
  echo "	arch = x86_64"
  echo "	arch = aarch64"
  echo "	license = MIT"
  for dep in "${depends[@]}"; do echo "	depends = $dep"; done
  for dep in "${optdepends[@]}"; do echo "	optdepends = $dep"; done
  echo "	provides = ramu"
  echo "	conflicts = ramu"
  echo "	options = !strip"
  echo "	options = !debug"
  echo "	source_x86_64 = ramu-$pkgver-x86_64.deb::$base/$x64_file"
  echo "	sha256sums_x86_64 = $x64_sum"
  echo "	source_aarch64 = ramu-$pkgver-aarch64.deb::$base/$arm_file"
  echo "	sha256sums_aarch64 = $arm_sum"
  echo
  echo "pkgname = ramu-bin"
} > "$out/.SRCINFO"
echo "Wrote ramu-bin $pkgver to $out"
